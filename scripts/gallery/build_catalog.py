def build() -> list[dict]:
    entries: list[dict] = []
    seen: set[str] = set()

    for c in CURATED:
        slug = slugify(c["title"])
        seen.add(slug)
        entries.append({
            "slug": slug,
            "title": c["title"],
            "subject": c["subject"],
            "category": c["category"],
            "tags": c["tags"],
            "level": c["level"],
            "minutes": c["minutes"],
            "status": "outline",
            "outline": c["outline"],
        })

    for subject, spec in INDEX.items():
        for topic in spec["topics"]:
            slug = slugify(topic)
            if slug in seen:
                continue
            seen.add(slug)
            entries.append({
                "slug": slug,
                "title": topic,
                "subject": subject,
                "category": spec["category"],
                "tags": [subject.lower()],
                "level": "Introductory",
                "minutes": 6,
                "status": "index",
                "outline": "",
            })

    entries.sort(key=lambda e: (e["category"], e["subject"], e["title"]))
    return entries


