def slugify(text: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return s[:80]


# ─────────────────────────────────────────────────────────────────────────────
# Curated topics — each carries a real structured brief the pipeline can teach.
# Keep briefs 120–260 words, with ## headings, an ordered list and a bullet
# list, so the layout engine has genuine structure to reason over.
# ─────────────────────────────────────────────────────────────────────────────

def brief(defn: str, ideas: list[str], steps: list[str], example: str,
          pitfalls: list[str], summary: str, matters: str = "", terms: list | None = None) -> str:
    """A structured teaching brief → ~8 slides. The web deck reveals each
    numbered step and bullet one click at a time."""
    parts: list[str] = [defn.strip(), ""]
    if matters:
        parts += ["## Why it matters", matters.strip(), ""]
    if terms:
        parts += ["## Key terms", *[f"- {t}" for t in terms], ""]
    parts += [
        "## The core ideas",
        *[f"- {i}" for i in ideas],
        "",
        "## How it works, step by step",
        *[f"{n}. {s}" for n, s in enumerate(steps, 1)],
        "",
        "## A worked example",
        example.strip(),
        "",
        "## Where people go wrong",
        *[f"- {p}" for p in pitfalls],
        "",
        "## The takeaway",
        summary.strip(),
    ]
    return "\n".join(parts)


